// Java is a case sensitive language

class CaseSensitiveLang {
	public static void main(String[] args) {
		int number = 10;
		int NumbeR = 11;
		int NUMBER = 12;
		int nUmBeR = 13;
		
		System.out.println("\n number = " + number);
		System.out.println("\n NumbeR = " + NumbeR);
		System.out.println("\n NUMBER = " + NUMBER);
		System.out.println("\n nUmBeR = " + nUmBeR);
	}
}