// Demonstrate char data type.
class CharExample {
  public static void main(String args[]) {
    char ch1, ch2;

    ch1 = 88;  // ASCII for X
    ch2 = 'Y';
    
    System.out.print("\n ch1 and ch2: ");
    System.out.println(ch1 + " " + ch2);
    System.out.println((int)ch1 + " " + (int)ch2);
	
  }
}